const { chromium } = require('playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');

let browser;
(async () => {
  browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const page = await browser.newPage({ viewport: { width: 780, height: 560 }, deviceScaleFactor: 2 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.join(__dirname, 'serif-lightning-inspect.html')).href);
  const frame = page.frames().find(frame => frame.parentFrame());
  await frame.waitForSelector('.serif-large');
  const pixels = () => frame.evaluate(() => document.querySelector('.serif-large').toDataURL());
  const first = await pixels();
  await page.waitForTimeout(240);
  if (first === await pixels()) throw new Error('The model does not spin.');
  await frame.locator('.serif-motion-button').click();
  await frame.waitForFunction(() => document.querySelector('.serif-large').dataset.motion === 'idle', null, { timeout: 4000 });
  await page.screenshot({ path: path.join(__dirname, 'serif-lightning-front.png') });
  const idle = await pixels();
  await page.waitForTimeout(120);
  if (idle !== await pixels()) throw new Error('The model does not settle at the first frame.');
  await frame.evaluate(() => window.__serifPreview.animated.forEach(model => model.draw(Math.PI / 4)));
  await page.screenshot({ path: path.join(__dirname, 'serif-lightning-angle.png') });
  await frame.evaluate(() => window.__serifPreview.animated.forEach(model => model.draw(Math.PI / 2)));
  await page.screenshot({ path: path.join(__dirname, 'serif-lightning-edge.png') });
  await frame.evaluate(() => window.__serifPreview.animated.forEach(model => model.draw(Math.PI)));
  await page.screenshot({ path: path.join(__dirname, 'serif-lightning-back.png') });
  await frame.evaluate(() => window.__serifPreview.animated.forEach(model => model.draw(0)));
  await page.setViewportSize({ width: 360, height: 680 });
  if (await frame.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)) throw new Error('The narrow preview overflows.');
  await page.screenshot({ path: path.join(__dirname, 'serif-lightning-mobile.png') });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await frame.locator('.serif-motion-button').click();
  const reduced = await pixels();
  await page.waitForTimeout(150);
  if (reduced !== await pixels()) throw new Error('Reduced-motion mode still spins.');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Verified spin, complete-turn stop, mobile layout, reduced motion, and no script errors.');
  await browser.close();
})().catch(async error => { console.error(error); await browser?.close(); process.exitCode = 1; });
